#!/usr/bin/env bash
# Hard-go: shadow-lower cc_result CCError face (error_face_frag) vs production face.
# Full cc_result.cch still hits the Result-macro / cpp wall; this gates the face.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../../../.." && pwd)"
SRC="$ROOT/examples/serdes/c/shadow/error_face_frag.cch"
PROD="$ROOT/out/include/ccc/cc_result.h"
SHADOW_SH="$ROOT/examples/serdes/c/shadow_lower.sh"
TMP="${TMPDIR:-/tmp}/cc_serdes_result_face_$$"
mkdir -p "$TMP"

if [[ ! -f "$PROD" ]]; then
  echo "FAIL: missing production $PROD (build headers first)"
  exit 1
fi

"$SHADOW_SH" "$SRC" -o "$TMP/error_face.shadow.h"

python3 - "$TMP/error_face.shadow.h" "$PROD" "$TMP" <<'PY'
import pathlib, re, sys
sh_path, pr_path, tmp = map(pathlib.Path, sys.argv[1:4])

def join_continued(text: str) -> str:
    lines = text.splitlines()
    out, buf = [], ""
    for ln in lines:
        buf = (buf + ln) if buf else ln
        if buf.rstrip().endswith("\\"):
            buf = buf.rstrip()[:-1] + " "
            continue
        out.append(buf)
        buf = ""
    if buf:
        out.append(buf)
    return "\n".join(out) + "\n"

def strip_comments(text: str) -> str:
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)

def extract_prod_face(text: str) -> str:
    """Keep CCError face through cc_error_exit; drop Result macros below."""
    text = strip_comments(text)
    # Cut before Result layout / CC_DECL_RESULT_SPEC.
    cut = re.search(r"\n/\*\s*\n \* Result type layout:", text)
    if not cut:
        cut = re.search(r"\n#define\s+CC_DECL_RESULT_SPEC\b", text)
    if cut:
        text = text[: cut.start()]
    return text

def norm(text: str, *, shadow: bool) -> str:
    text = join_continued(strip_comments(text))
    if not shadow:
        text = extract_prod_face(text)
    lines, defs = [], []
    for ln in text.splitlines():
        s = ln.rstrip()
        if shadow and s.startswith("/* generated by"):
            continue
        if shadow and s.startswith("/* Beachhead:"):
            continue
        if s == "#pragma once":
            continue
        if re.match(r"#ifndef\s+CC_RESULT_H\b", s):
            continue
        if re.match(r"#define\s+CC_RESULT_H\b", s):
            continue
        if s.startswith("#endif") and ("CC_RESULT" in s or s == "#endif"):
            continue
        if re.match(r"\s*#line\s", s):
            continue
        if shadow and s == "#include <stddef.h>":
            continue
        if re.match(r"#include\s+<ccc/cc_compat", s):
            continue
        if not s.strip():
            continue
        if s.startswith("#define "):
            defs.append(re.sub(r"\s+", " ", s).strip())
            continue
        if re.match(r"\s*(case\b|default\s*:)", s):
            s = "        " + s.lstrip()
        elif re.match(r"\s*CC_ERR_", s):
            s = "    " + s.lstrip()
        s = re.sub(r"\s+;", ";", s)
        s = re.sub(r"\s*/\*.*$", "", s)
        s = re.sub(r"\s+", " ", s).strip()
        # Glue single-statement if bodies onto the controlling if.
        if lines and lines[-1].startswith("if (") and not lines[-1].endswith(";") \
           and not s.startswith("if ") and not s.startswith("}") \
           and not s.startswith("static ") and not s.startswith("typedef "):
            lines[-1] = lines[-1] + " " + s
            continue
        lines.append(s)
    head = [s for s in lines if s.startswith("#include ")]
    body = [s for s in lines if not s.startswith("#include ")]
    return "\n".join(head + sorted(defs) + body) + "\n"

ns = norm(sh_path.read_text(), shadow=True)
np = norm(pr_path.read_text(), shadow=False)
(tmp / "shadow.norm.h").write_text(ns)
(tmp / "prod.norm.h").write_text(np)
if ns != np:
    print("FAIL: normalized shadow vs production cc_result face differs")
    import subprocess
    subprocess.run(["diff", "-u", str(tmp / "prod.norm.h"), str(tmp / "shadow.norm.h")])
    sys.exit(1)
print("diff_stdlib_result_face: normalized C surface matches production face")
PY

cat > "$TMP/use.c" <<'EOF'
#include "error_face.h"
int main(void) {
    CCError e = CC_ERROR(CC_ERR_NULL, "x");
    (void)cc_error_str(e);
    (void)cc_error_kind_str(e.kind);
    return e.kind == CC_ERR_NULL ? 0 : 1;
}
EOF
cp "$TMP/error_face.shadow.h" "$TMP/error_face.h"
cc -std=c11 -I"$TMP" -I"$ROOT/out/include" -c "$TMP/use.c" -o "$TMP/use.o"
echo "diff_stdlib_result_face: host cc -c OK"
rm -rf "$TMP"
